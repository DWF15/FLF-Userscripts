const assert=require('node:assert/strict');
const {extract}=require('../mail-to-clio.user.js');
const p=extract('Case Number: 26SL-AC01234\nPlaintiff: Example Property LLC\nDefendant: Sample Tenant\nTicket Number: 123456789, 987654321\nHearing scheduled for 11/05/2026 at 9:30 AM');
assert.equal(p.fields['Case Number'],'26SL-AC01234');
assert.equal(p.fields['Ticket Number'],'123456789, 987654321');
assert.match(p.fields['Hearing Details'],/9:30 AM/);
assert.equal(extract('Hearing 11/05/2026').fields['Hearing Details'],undefined);
assert.equal(extract('Filed 11/05/2026 at 9:30 AM').fields['Hearing Details'],undefined);
assert.equal(extract('Case Number: 26SL-AC01234\nOther case: 26SL-AC05555').fields['Case Number'],undefined);
assert.equal(extract('Plaintiff: One\nPlaintiff: Two').fields.Plaintiff,undefined);
assert.equal(extract('Hearing 11/05/2026 at 9:30 AM\nHearing 12/05/2026 at 10:00 AM').fields['Hearing Details'],undefined);
assert.ok(extract('A judgment entered').keywords.includes('judgment'));
assert.ok(extract('New custom event',['custom event']).keywords.includes('custom event'));
console.log('10 parser assertions passed');
const notice=extract('ELECTRONIC NOTICE OF ENTRY\nSt Louis County - Circuit Court\nCASE NO: 26SL-AC01234 - EXAMPLE PROPERTY LLC V. SAMPLE TENANT\n10/9/26 11:48 AM Hearing Scheduled None entered at this time\nScheduled For\n\n11/18/26 9:00 AM - EXAMPLE JUDGE');
assert.equal(notice.fields['Case Number'],'26SL-AC01234');
assert.equal(notice.fields.County,'St Louis County');
assert.equal(notice.fields['Court Level'],'Circuit Court');
assert.equal(notice.fields.Plaintiff,'EXAMPLE PROPERTY LLC');
assert.equal(notice.fields.Defendant,'SAMPLE TENANT');
assert.match(notice.fields['Hearing Details'],/11\/18\/26 9:00 AM/);
assert.equal(extract('10/9/26 11:48 AM Hearing Scheduled').fields['Hearing Details'],undefined);
assert.ok(extract('Hearing continued').notice_flags.includes('continuance'));
assert.ok(extract('Hearing cancelled').notice_flags.includes('cancellation'));
assert.equal(extract('Scheduled For\nSummons issued\n10/9/26 11:49 AM').fields['Hearing Details'],undefined);
console.log('10 additional Case.net/parser assertions passed');
assert.equal(extract('Judge Assigned\t37W\t10/9/26 11:48 AM').fields['Court Division'],'37W');
assert.equal(extract('Judge Assigned\n37W\n10/9/26 11:48 AM').fields['Court Division'],'37W');
assert.equal(extract('Judge Assigned 10/9/26 11:48 AM').fields['Court Division'],undefined);
assert.equal(extract('Judge Assigned 37W\nJudge Assigned 38W').fields['Court Division'],undefined);
assert.equal(extract('Division: 42\nJudge Assigned 37W').fields['Court Division'],'42');
console.log('5 division assertions passed');
